package model

import (
	"go.mongodb.org/mongo-driver/v2/bson"
)

type Analysis struct { // validate in these are not required as its a pointer and generated by backend
	Score      int      `bson:"score" json:"score"`
	FitLabel   string   `bson:"fit_label" json:"fit_label"`
	Strengths  []string `bson:"strengths" json:"strengths"`
	Gaps       []string `bson:"gaps" json:"gaps"`
	Tip        string   `bson:"tip" json:"tip"`
	AnalyzedAt string   `bson:"analyzed_at" json:"analyzed_at"`
}

type Application struct {
	ID             bson.ObjectID `bson:"_id" json:"_id" validate:"required"`
	UserID         bson.ObjectID `bson:"user_id" json:"user_id" validate:"required"`
	Company        string        `bson:"company" json:"company" validate:"required"`
	Role           string        `bson:"role" json:"role" validate:"required"`
	JobDescription string        `bson:"job_description" json:"job_description" validate:"required"`
	ResumeVersion  string        `bson:"resume_version" json:"resume_version" validate:"required"`
	Status         string        `bson:"status" json:"status" validate:"oneof=Saved Applied Interview Offer Rejected"`
	AppliedDate    *string       `bson:"applied_date" json:"applied_date"`
	Notes          *string       `bson:"notes" json:"notes"` // * makes it a pointer whose zero value is nil.
	AiAnalysis     *Analysis     `bson:"ai_analysis" json:"ai_analysis"`
	CreatedAt      string        `bson:"created_at" json:"created_at" validate:"required"`
	UpdatedAt      string        `bson:"updated_at" json:"updated_at" validate:"required"`
}
